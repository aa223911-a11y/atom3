# 원소 특징 출력 함수
def show_element(number, selected):
    st.subheader(str(number) + "번 원소의 특징")

    for j in selected:
        if j == 1:
            st.write("이름:", elements[number - 1][0])
        elif j == 2:
            st.write("원소 종류:", elements[number - 1][1])
        elif j == 3:
            st.write("전자 특징:", elements[number - 1][2])
        elif j == 4:
            st.write("주기와 족:", elements[number - 1][3])
        elif j == 5:
            st.write("원소의 성질:", elements[number - 1][4])
        else:
            st.write("잘못된 선택입니다.")


