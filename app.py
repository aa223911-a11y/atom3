# 결과 출력 버튼
if st.button("원소 특징 확인하기"):

    if len(selected) == 0:
        st.warning("확인할 정보를 선택해 주세요.")

    elif number >= 1 and number <= 20:
        show_element(int(number), selected)

    else:
        st.error("다시 선택해 주세요.")
